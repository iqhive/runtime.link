// UnmarshalJSON reads the two shapes of a tool choice, a string naming a mode or
// an object naming a function. Decoding has to pick between them first, because
// a tagged union gives up at the first case of a different shape to the value.
func (c *ToolChoice) UnmarshalJSON(data []byte) error {
	if !bytes.HasPrefix(bytes.TrimSpace(data), []byte("{")) {
		type mode ToolChoice // keeps the promoted methods, but not this one.
		return (*mode)(c).UnmarshalJSON(data)
	}
	var named struct {
		Type     string   `json:"type"`
		Function Function `json:"function"`
	}
	if err := json.Unmarshal(data, &named); err != nil {
		return err
	}
	if named.Type != "function" {
		return fmt.Errorf("unsupported tool choice type %q", named.Type)
	}
	*c = ToolChoices.Specific.As(named.Function)
	return nil
}

